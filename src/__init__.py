"""Исходный код проекта notiocer.

Пакет организован по принципам чистой архитектуры: зависимости
направлены внутрь, а внешние технологии подключаются через порты.
Слои и их роли:

- :mod:`src.domain` — доменный слой: сущности :class:`Invoice`
  и :class:`InvoiceMessage` и доменные сервисы, выражающие правила
  предметной области (отбор счетов, группировка по получателям,
  формирование сообщений). Не зависит от инфраструктуры.
- :mod:`src.application` — прикладной слой: команды, DTO, порты
  и сценарии использования. Оркестрирует доменные сервисы,
  но взаимодействует с внешним миром только через ``Protocol``-порты.
- :mod:`src.infra` — инфраструктурный слой: адаптеры к внешним
  системам (Excel, Exchange, AX), реализующие порты прикладного слоя.
- :mod:`src.controllers` — входные точки: контроллеры, которые
  готовят входные данные и вызывают сценарии использования.
- :mod:`src.utils` — вспомогательные утилиты, не привязанные
  к конкретному слою (например, декоратор :func:`retry_sync`).

Направление зависимостей::

    controllers ──▶ application ──▶ domain
                         ▲
                         │ (реализует порты)
                       infra

    utils — используется любым слоем, сам ни от кого не зависит

Домен ничего не знает о прикладном слое; прикладной слой не знает
об инфраструктуре; инфраструктура и контроллеры зависят от
прикладного слоя, но не наоборот. ``utils`` стоит особняком:
это технические хелперы без бизнес-логики, которые может
использовать любой слой, но сам ``utils`` не импортирует
ничего из ``domain``, ``application``, ``infra`` или ``controllers``.
"""

