"""Адаптеры, запускающие внешние процессы через :mod:`subprocess`.

Содержит реализации портов, которым нужно вызвать стороннюю программу
или скрипт и дождаться завершения. В отличие от остальных групп
адаптеров (``ax_adapters``, ``excel_readers``, ``exchange_adapters``),
здесь нет прямой работы с библиотекой: взаимодействие идёт через
запуск дочернего процесса операционной системы.

Состав пакета:

- :class:`QlikViewMacrosRunner` — запускает макрос QlikView через
  внешний исполняемый файл с настраиваемым таймаутом (реализует порт
  ``MacrosRunner``).

Общие принципы:

- команда передаётся списком аргументов (первый элемент — путь к
  исполняемому файлу), а не строкой, чтобы избежать подстановки shell
  и проблем с пробелами в путях;
- ошибки внешнего процесса не проглатываются: таймаут преобразуется
  в :class:`TimeoutError`, ненулевой код возврата — в
  :class:`RuntimeError` с диагностикой из stderr;
- адаптеры этой группы не содержат бизнес-логики: решение о том,
  когда и зачем запускать процесс, принимается в слоях
  ``domain``/``application``.
"""

