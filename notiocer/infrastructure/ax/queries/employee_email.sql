SELECT DISTINCT
    et.EMPLID,
    et.STATUS,
    et.HLEmplDepartment,
    ad.EMAIL,
    heh.WorkStatus
FROM EMPLTABLE et
LEFT JOIN DIRPARTYADDRESSRELATIONSHIP dpar
    ON dpar.PARTYID = et.PARTYID
LEFT JOIN DIRPARTYADDRESSRELATIONSHI1066 dpar1
    ON dpar1.PARTYADDRESSRELATIONSHIPRECID = dpar.RECID
LEFT JOIN ADDRESS ad
    ON ad.DATAAREAID = dpar1.REFCOMPANYID
    AND ad.RECID = dpar1.ADDRESSRECID
LEFT JOIN HLEMPLHISTORY heh
    ON et.EMPLID = heh.EMPLID
WHERE LEN(ad.EMAIL) > 0
    AND et.EMPLID = ?
